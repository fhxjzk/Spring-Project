-- 05. 채팅 및 알림 테이블

-- 1. 채팅 메시지
CREATE TABLE PROLINK_CHAT_MESSAGE (
    MESSAGE_ID NUMBER(19) PRIMARY KEY,
    ROOM_ID VARCHAR2(18) NOT NULL,
    SENDER VARCHAR2(100) NOT NULL,
    CONTENT VARCHAR2(4000) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE SEQUENCE SEQ_PROLINK_CHAT_MESSAGE
START WITH 1
INCREMENT BY 1
NOCACHE
NOCYCLE;

CREATE INDEX IDX_PROLINK_CHAT_ROOM
ON PROLINK_CHAT_MESSAGE (ROOM_ID, MESSAGE_ID);


-- 2. 알림
CREATE TABLE PROLINK_NOTIFICATION (
    NOTIFICATION_ID NUMBER(19) PRIMARY KEY,
    RECEIVER_SEQ NUMBER(19) NOT NULL,
    NOTIFICATION_TYPE VARCHAR2(50) NOT NULL,
    TITLE VARCHAR2(200) NOT NULL,
    MESSAGE VARCHAR2(1000) NOT NULL,
    REFERENCE_ID NUMBER(19),
    IS_READ CHAR(1) DEFAULT 'N' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_PROLINK_NOTIFICATION_READ
        CHECK (IS_READ IN ('Y', 'N'))
);

CREATE SEQUENCE SEQ_PROLINK_NOTIFICATION
START WITH 1
INCREMENT BY 1
NOCACHE
NOCYCLE;

CREATE INDEX IDX_PROLINK_NOTIFICATION_RECEIVER
ON PROLINK_NOTIFICATION (RECEIVER_SEQ, CREATED_AT DESC);